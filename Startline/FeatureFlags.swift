import Foundation

/// 배치 계산 같은 격리 밖 코드에서도 읽으므로 `nonisolated` 다.
/// 값이 바뀌지 않는 상수 모음이라 어디서 읽어도 안전하다.
nonisolated enum FeatureFlags {

    /// 그리드 막대에 마우스를 올렸을 때 나오는 미리보기.
    ///
    /// 클릭을 가로채던 문제는 창 안 오버레이로 옮겨 해결했지만(BL-023),
    /// **미리보기 자체가 필요한지가 불확실해 당분간 꺼 둔다.**
    /// 끄고 지내면서 실제로 아쉬운지 확인한다. (BL-044)
    static let hoverPreview = false

    /// 시작할 때를 놓친 할 일을 **오늘 칸에도** 한 번 더 그리는 것.
    ///
    /// 착수 쪽은 이미 세 군데가 덮는다 — 그리드 본 막대, 「오늘 시작할 일」 배너, 알림 3단계.
    /// 비어 있던 것은 마감 쪽이었고, 그것은 우측 패널 「기한 지난 할 일」이 맡게 됐다. (BL-051)
    ///
    /// 반면 이 막대는 **그리드에 사실이 아닌 위치를 하나 더 그린다.** 그 대가로 오독이
    /// 두 번 났다 — 하나의 막대가 끊어져 보이고, 8월 마감이 9월 일로 읽혔다. (BL-050)
    ///
    /// **끄고 지내면서 실제로 아쉬운지 확인한다.** 켜려면 `true` 로 바꾸면 그만이다.
    /// 코드는 그대로 남아 있어 즉시 이전 동작으로 돌아온다.
    static let todayEcho = false
}
